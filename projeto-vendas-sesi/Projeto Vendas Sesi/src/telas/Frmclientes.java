    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // botao excluir
        if (txtcodigo.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Selecione um cliente na Consulta antes de excluir.");
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(null, "Tem certeza que deseja excluir?");

        if (confirmacao != JOptionPane.YES_OPTION) {
            return;
        }

        Connection conexao = conectar();
        if (conexao == null) {
            return;
        }
        try {
            String sql = "DELETE FROM tb_clientes WHERE ID=?";
            PreparedStatement stmt = (PreparedStatement) conexao.prepareStatement(sql);
            stmt.setInt(1, Integer.parseInt(txtcodigo.getText()));

            stmt.executeUpdate();
            JOptionPane.showMessageDialog(null, "Cliente excluído com sucesso!");
            conexao.close();
        } catch (SQLException erro) {
            JOptionPane.showMessageDialog(null, "Erro ao excluir: " + erro.getMessage());
        }
    }//GEN-LAST:event_jButton4ActionPerformed

    private void formWindowActivated(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowActivated
        Connection conexao = conectar();
        if (conexao == null) {
            return;
        }

        try {
            String sql = "SELECT ID, NOME, RG, CPF, EMAIL, TELEFONE, CELULAR, CEP, "
                    + "ENDERECO, NUMERO, COMPLEMENTO, BAIRRO, CIDADE, estado "
                    + "FROM tb_clientes WHERE NOME LIKE ?";

            PreparedStatement stmt = (PreparedStatement) conexao.prepareStatement(sql);
            stmt.setString(1, "%" + txtpesquisa.getText() + "%");
            var rs = stmt.executeQuery();

            DefaultTableModel modelo = new DefaultTableModel();
            modelo.addColumn("Código");
            modelo.addColumn("Nome");
            modelo.addColumn("RG");
            modelo.addColumn("CPF");
            modelo.addColumn("E-mail");
            modelo.addColumn("Telefone");
            modelo.addColumn("Celular");
            modelo.addColumn("Cep");
            modelo.addColumn("Endereço");
            modelo.addColumn("N°");
            modelo.addColumn("Comp");
            modelo.addColumn("Bairro");
            modelo.addColumn("Cidade");
            modelo.addColumn("UF");

            while (rs.next()) {
                Object[] linha = {
                    rs.getInt("ID"), rs.getString("NOME"), rs.getString("RG"),
                    rs.getString("CPF"), rs.getString("EMAIL"), rs.getString("TELEFONE"),
                    rs.getString("CELULAR"), rs.getString("CEP"), rs.getString("ENDERECO"),
                    rs.getInt("NUMERO"), rs.getString("COMPLEMENTO"), rs.getString("BAIRRO"),
                    rs.getString("CIDADE"), rs.getString("estado")
                };
                modelo.addRow(linha);
            }

            tabelaclientes.setModel(modelo);
            conexao.close();
        } catch (SQLException erro) {
            JOptionPane.showMessageDialog(null, "Erro ao pesquisar: " + erro.getMessage());
        }
    }//GEN-LAST:event_formWindowActivated

