    private void btnsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsalvarActionPerformed
        // boto salvar
        Connection conexao = conectar();

        if (conexao == null) {
            return;
        }

        try {
            String sql = "INSERT INTO tb_clientes (NOME, RG, CPF, EMAIL, TELEFONE, "
                    + "CELULAR, CEP, ENDERECO, NUMERO, COMPLEMENTO, BAIRRO, CIDADE, estado) "
                    + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

            PreparedStatement stmt = (PreparedStatement) conexao.prepareStatement(sql);
            stmt.setString(1, txtnome.getText());
            stmt.setString(2, txtrg.getText());
            stmt.setString(3, txtcpf.getText());
            stmt.setString(4, txtemail.getText());
            stmt.setString(5, txtfixo.getText());
            stmt.setString(6, txtcel.getText());
            stmt.setString(7, txtcep.getText());
            stmt.setString(8, txtend.getText());
            stmt.setInt(9, Integer.parseInt(txtnumero.getText()));
            stmt.setString(10, txtcomplemento.getText());
            stmt.setString(11, txtbairro.getText());
            stmt.setString(12, txtcidade.getText());
            stmt.setString(13, cbuf.getSelectedItem().toString());

            stmt.executeUpdate();
            JOptionPane.showMessageDialog(null, "Cliente salvo com sucesso!");
            conexao.close();

        } catch (SQLException erro) {
            JOptionPane.showMessageDialog(null, "Erro ao salvar: " + erro.getMessage());
        }

    }//GEN-LAST:event_btnsalvarActionPerformed

